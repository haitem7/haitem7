def sha256_csp(src: str) -> str:
    return "'sha256-" + base64.b64encode(hashlib.sha256(src.encode()).digest()).decode() + "'"


def write_site_files(data: dict) -> None:
    """robots.txt, sitemap.xml and the two security-header files.

    The CSP hashes are computed from the same constants the pages are built
    from, so a new inline handler can never silently break the policy: change
    the handler, rebuild, and _headers follows.
    """
    paths = data["_pages"]

    # -- robots.txt --------------------------------------------------------
    robots = ["User-agent: *", "Allow: /", ""]
    if SITE_URL:
        robots.append(f"Sitemap: {SITE_URL}/sitemap.xml")
    else:
        robots.append("# Sitemap: set SITE_URL and rebuild to emit sitemap.xml")
    (ROOT / "robots.txt").write_text("\n".join(robots) + "\n", "utf-8")

    # -- sitemap.xml -------------------------------------------------------
    # Absolute URLs only: a sitemap with relative locations is rejected
    # outright, so it is written only once the domain is known.
    if SITE_URL:
        urls = ""
        for path in paths:
            loc = f"{SITE_URL}/{path}"
            # hreflang siblings are the same page in the other languages,
            # which for /en/export/ is /export/ and /ar/export/ — not /en/.
            stem = path.split("/")[-1] if "/" in path else ("" if path in ("", "en", "ar") else path)
            sibs = [p for p in paths
                    if (p.split("/")[-1] if "/" in p else ("" if p in ("", "en", "ar") else p)) == stem]
            alts = "".join(
                f'<xhtml:link rel="alternate" '
                f'hreflang="{"fr" if q in ("", "export") else q.split("/")[0]}" '
                f'href="{SITE_URL}/{q}"/>' for q in sibs
            )
            urls += (f"<url><loc>{loc}</loc>{alts}"
                     f'<xhtml:link rel="alternate" hreflang="x-default" '
                     f'href="{SITE_URL}/"/>'
                     f"<changefreq>monthly</changefreq></url>")
        (ROOT / "sitemap.xml").write_text(
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
            'xmlns:xhtml="http://www.w3.org/1999/xhtml">'
            f"{urls}</urlset>\n", "utf-8")

    # -- Content-Security-Policy -------------------------------------------
    # If the quotation form posts to a third party (Formspree, EmailJS…),
    # that origin has to be allowed or the browser blocks the submission and
    # the buyer sees a silent failure. Derived, never hand-maintained.
    endpoints = set()
    for key, c in data.items():
        if key == "_pages":
            continue
        endpoints.add(c["rfq"].get("endpoint", "").strip())
        endpoints.add(c["shop"]["checkout"].get("endpoint", "").strip())
    origins = sorted({
        f"{(u := urlsplit(url)).scheme}://{u.netloc}"
        for url in endpoints if url.startswith("http")
    })
    extra_src = (" " + " ".join(origins)) if origins else ""

    inline = sha256_csp(JS_NOJS)
    handlers = " ".join(sorted({sha256_csp(JS_FONT_SWAP), sha256_csp(JS_IMG_FALLBACK)}))
    csp = (
        "default-src 'self'; "
        f"script-src 'self' {inline} 'unsafe-hashes' {handlers}; "
        "style-src 'self' https://fonts.googleapis.com; "
        "font-src 'self' https://fonts.gstatic.com; "
        "img-src 'self' data:; "
        "media-src 'self'; "
        f"connect-src 'self'{extra_src}; "
        f"form-action 'self'{extra_src}; "
        "base-uri 'self'; "
        "object-src 'none'; "
        "frame-ancestors 'none'; "
        "upgrade-insecure-requests"
    )
    common = [
        ("Content-Security-Policy", csp),
        ("Strict-Transport-Security", "max-age=31536000; includeSubDomains"),
        ("X-Content-Type-Options", "nosniff"),
        ("Referrer-Policy", "strict-origin-when-cross-origin"),
        ("Permissions-Policy", "geolocation=(), microphone=(), camera=(), payment=(), usb=()"),
        ("Cross-Origin-Opener-Policy", "same-origin"),
    ]

    # Netlify / Cloudflare Pages
    head = "/*\n" + "".join(f"  {k}: {v}\n" for k, v in common)
    head += ("/assets/*\n  Cache-Control: public, max-age=31536000, immutable\n"
             "/*.html\n  Cache-Control: public, max-age=0, must-revalidate\n")
    (ROOT / "_headers").write_text(head, "utf-8")

    # Apache / cPanel, which is what most Algerian shared hosting runs
    ht = ["# Generated by build.py — do not edit by hand.",
          "<IfModule mod_headers.c>"]
    ht += [f'  Header always set {k} "{v}"' for k, v in common]
    ht += ["</IfModule>", "",
           "<IfModule mod_rewrite.c>",
           "  RewriteEngine On",
           "  RewriteCond %{HTTPS} !=on",
           "  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]",
           "</IfModule>", "",
           "<IfModule mod_deflate.c>",
           "  AddOutputFilterByType DEFLATE text/html text/css application/javascript "
           "image/svg+xml application/json",
           "</IfModule>", "",
           "Options -Indexes", ""]
    (ROOT / ".htaccess").write_text("\n".join(ht), "utf-8")


def main() -> None:
    data = {l: json.loads((ROOT / "content" / f"{l}.json").read_text("utf-8")) for l in LOCALES}
    # Two pages per language. The language switcher must stay on the page
    # the reader is already on: a shopper sent from the Arabic shop to the
    # French export page has lost their place, not changed language.
    views = {"shop": [shop_view(d) for d in data.values()],
             "export": [export_view(d) for d in data.values()]}
    pages = []
    for kind, vs in views.items():
        alts = [{"lang": v["lang"], "path": v["path"], "label": v["label"]} for v in vs]
        for v in vs:
            out = ROOT / (v["path"] + "/" if v["path"] else "") / "index.html"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(page(v, alts), "utf-8")
            pages.append(v["path"])
            print(f"  {out.relative_to(ROOT)}  ({len(out.read_text('utf-8')):,} bytes)")
    data["_pages"] = pages
    write_ratio_css()
    write_site_files(data)
    extra = ["robots.txt", "_headers", ".htaccess"] + (["sitemap.xml"] if SITE_URL else [])
    print("  " + ", ".join(extra))
    if not SITE_URL:
        print("  ! SITE_URL is empty: no sitemap.xml, no og:image, relative canonical.")
        print("    Once the domain exists:  SITE_URL=https://example.dz python3 build.py")


if __name__ == "__main__":
    print("TLEMCENYA — rendering pages")
    main()
