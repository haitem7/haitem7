def jsonld(c: dict) -> str:
    """Structured data for the entity, the mill and the oil.

    Two things are deliberately absent. There is no aggregateRating: Google
    forbids review markup you cannot show on the page, and inventing stars
    is the fastest way to lose rich results permanently. There are no
    offers until content/*.json carries real prices — an offer is a public
    commercial commitment, and a wrong one is quoted back at you.
    """
    f, L, m = c["footer"], c["location"], c["meta"]
    S = c["schema"]
    page_url = (SITE_URL or "") + "/" + (c["path"] + "/" if c["path"] else "")
    # The company and the mill are one entity across all six pages, so their
    # @id is pinned to the site root. Only the Product differs per page.
    root = (SITE_URL or "") + "/"
    brand_name = c.get("brand", BRAND_DEFAULT)

    street = [x for x in f["address"][1:] if "TODO" not in x]
    postal = {
        "@type": "PostalAddress",
        "streetAddress": street[0] if street else "",
        "addressLocality": "Tlemcen",
        "postalCode": "13000",
        "addressCountry": "DZ",
    }

    org = {
        "@type": "Organization",
        "@id": root + "#org",
        "name": brand_name,
        "url": root,
        "description": m["description"],
        "email": f["email"],
        "address": postal,
        "location": {"@id": root + "#mill"},
    }
    if "TODO" not in f["phone"]:
        org["telephone"] = f["phone"].replace(" ", "")

    mill = {
        "@type": "Place",
        "@id": root + "#mill",
        "name": S["mill_name"],
        "address": postal,
    }
    gps = L.get("gps", "").strip()
    if gps:
        lat, _, lon = gps.partition(",")
        mill["geo"] = {
            "@type": "GeoCoordinates",
            "latitude": lat.strip(),
            "longitude": lon.strip(),
        }
        mill["hasMap"] = ("https://www.google.com/maps/search/?api=1&query="
                          + quote(gps))

    P = c["catalog"] if c["kind"] == "shop" else c["products"]
    product = {
        "@type": "Product",
        "@id": page_url + "#oil",
        "name": S["product_name"],
        "description": P["lede"],
        "category": "Extra virgin olive oil",
        "brand": {"@type": "Brand", "name": brand_name},
        "manufacturer": {"@id": org["@id"]},
        "countryOfOrigin": {"@type": "Country", "name": "DZ"},
    }
    offers = []
    for i in P["items"]:
        price = str(i.get("price", "")).strip()
        if not price:
            continue
        offers.append({
            "@type": "Offer",
            "name": i["size"],
            "price": price,
            "priceCurrency": "DZD",
            "availability": "https://schema.org/InStock",
        })
    if offers:
        product["offers"] = offers

    graph = {"@context": "https://schema.org", "@graph": [org, mill, product]}
    payload = json.dumps(graph, ensure_ascii=False, separators=(",", ":"))
    # No "</" can reach the parser inside a script element.
    payload = payload.replace("</", "<\\/")
    return f'<script type="application/ld+json">{payload}</script>'


def wa_link(c: dict) -> str:
    """Floating WhatsApp button, or nothing while the number is a placeholder.

    A button that opens a chat with a number that does not exist costs more
    trust than it buys, so it renders only once footer.phone is real.
    """
    f = c["footer"]
