# A range is "<number> <dash> <number>" with whitespace around the dash,
# so a hyphenated code such as TLM-25-114 is never matched.
RANGE = re.compile(r"\d[\d.,\u202f]*\s[–—-]\s\d[\d.,]*\s?[%\u066a]?")
LRI, PDI = "\u2066", "\u2069"


def e(s: object) -> str:
    return html.escape(str(s), quote=True)


def num(s: object, lang: str) -> str:
    """Escape, and in RTL pin numeric ranges to LTR.

    Arabic is an RTL paragraph, and digits are bidi-weak: without an
    explicit isolate the browser renders "18 - 22%" as "22% - 18".
    """
    if lang != "ar":
        return e(s)
    # Unicode isolates rather than markup: these survive inside <option>,
    # attribute values and plain text, where a <span> cannot go.
    return e(RANGE.sub(lambda m: LRI + m.group(0) + PDI, str(s)))


# Aspect ratios are collected as they are emitted and written out as real
# CSS classes, so no page carries a style="" attribute. That keeps the
# Content-Security-Policy free of 'unsafe-inline' / 'unsafe-hashes' for
# styles: an attacker who finds an injection point still cannot restyle the
# page into a convincing fake form.
RATIOS: set[str] = set()


def ratio_class(r: str) -> str:
    r = " ".join(str(r).split())
    RATIOS.add(r)
    return "ar-" + re.sub(r"[^0-9a-z]+", "-", r.lower()).strip("-")


def write_ratio_css() -> None:
    lines = ["/* Generated by build.py — do not edit. */", "@layer components {"]
    for r in sorted(RATIOS):
        lines.append(f"  .{ratio_class(r)} {{ aspect-ratio: {r}; }}")
    lines.append("}")
    (ROOT / "src" / "_ratios.css").write_text("\n".join(lines) + "\n", "utf-8")


